import { chmod, mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { stringify as stringifyToml } from 'smol-toml';
import { stringify as stringifyYaml } from 'yaml';
import type { ServiceId } from './broker.js';
import { CATALOG, commandLine, entryName, HERMES_APPROVAL_TIMEOUT_MS, hermesEntryName, serviceEnv, shellQuote, type CatalogContext } from './catalog.js';
import type { TwakeAiConfig } from './config.js';
import { entryPoint } from './installer.js';

export interface ServerEntry {
  command: string;
  args: string[];
  env: Record<string, string>;
}

export interface ExportOptions {
  agent: string;
  services: ServiceId[];
  /** the MCP servers themselves with their full environment, instead of `mcp-twake-ai run` */
  raw: boolean;
  /** TWAKE_AI_HOME of the export: the agent must use the same account (spec §5.3, several accounts) */
  twakeAiHome?: string;
}

/** What an agent starts for one service through the launcher: node, mcp-twake-ai's command, `run <service> --agent <id>`. */
export function launcherEntry(service: ServiceId, agent: string, ctx: CatalogContext, env: Record<string, string> = {}): ServerEntry {
  return { command: ctx.nodePath, args: [ctx.cliPath, 'run', service, '--agent', agent], env };
}

/** What an agent starts for one service. The environment is built in both cases, so a missing connection fails here. */
export async function serverEntry(service: ServiceId, agent: string, raw: boolean, ctx: CatalogContext, extra: Record<string, string> = {}): Promise<ServerEntry> {
  const env = serviceEnv(service, agent, ctx);
  if (!raw) return launcherEntry(service, agent, ctx, extra);
  return { command: ctx.nodePath, args: [await entryPoint(ctx.paths, service)], env: { ...env, ...extra } };
}

/** The services worth exporting: those found for the domain, Drive once connected, and Chat (its device is created on export). */
export function defaultServices(config: TwakeAiConfig): ServiceId[] {
  const found = config.environment.services;
  return (['mail', 'dav', 'drive', 'chat', 'space', 'project'] as const).filter((service) => {
    if (service === 'drive') return config.drive !== undefined;
    if (service === 'chat') return true;
    return found[service] !== undefined;
  });
}

const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;
const withEnv = (entry: ServerEntry, env: Record<string, string> = entry.env) => ({
  command: entry.command,
  args: entry.args,
  ...(Object.keys(env).length ? { env } : {}),
});
/** POSIX shell syntax (`set -a; . ./mail.env; set +a`): single quotes, so nothing in a value is ever run or expanded. */
const envFile = (env: Record<string, string>) =>
  Object.entries(env)
    .map(([key, value]) => `${key}=${shellQuote(value)}`)
    .join('\n') + '\n';

/** Every file of the export, by name. Nothing secret: tokens only ever come from `mcp-twake-ai token`. */
export async function exportFiles(options: ExportOptions, ctx: CatalogContext): Promise<Record<string, string>> {
  const extra: Record<string, string> = options.twakeAiHome ? { TWAKE_AI_HOME: options.twakeAiHome } : {};
  const entries = new Map<ServiceId, ServerEntry>();
  for (const service of options.services) entries.set(service, await serverEntry(service, options.agent, options.raw, ctx, extra));
  const byName = <T>(name: (service: ServiceId) => string, shape: (entry: ServerEntry, service: ServiceId) => T) =>
    Object.fromEntries([...entries].map(([service, entry]) => [name(service), shape(entry, service)]));
  const files: Record<string, string> = {
    'mcpServers.json': json({ mcpServers: byName(entryName, (entry) => withEnv(entry)) }),
    'vscode-mcp.json': json({ servers: byName(entryName, (entry) => ({ type: 'stdio', ...withEnv(entry) })) }),
    'hermes.yaml': stringifyYaml({
      mcp_servers: byName(hermesEntryName, (entry, service) => ({
        // for the agent id hermes the environment already waits longer for approvals (catalog): the entry stays the one setup writes
        ...(options.agent === 'hermes' ? withEnv(entry) : withEnv(entry, { ...entry.env, [`${CATALOG[service].approval}_APPROVAL_TIMEOUT_MS`]: HERMES_APPROVAL_TIMEOUT_MS })),
        timeout: 420,
        elicitation: { enabled: true, timeout: 300 },
      })),
    }),
    'codex.toml': stringifyToml({ mcp_servers: byName(entryName, (entry) => withEnv(entry)) }),
    'claude-code.sh': [
      '#!/bin/sh',
      '# Adds the Twake.ai MCP servers to Claude Code (user scope). Generated by mcp-twake-ai export.',
      'set -e',
      // remove first: running the script again (after an export again) must replace the entries, not stop on them
      ...[...entries].flatMap(([service, entry]) => [
        `claude mcp remove --scope user ${entryName(service)} >/dev/null 2>&1 || true`,
        `claude mcp add-json --scope user ${entryName(service)} ${shellQuote(JSON.stringify({ type: 'stdio', ...withEnv(entry) }))}`,
      ]),
      '',
    ].join('\n'),
    'commands.txt': [...entries]
      .map(([service, entry]) => `# ${entryName(service)} (environment: ${service}.env)\n${commandLine([entry.command, ...entry.args], ctx.platform)}\n`)
      .join('\n'),
    'README.md': readme(options),
  };
  for (const service of options.services) files[`${service}.env`] = envFile({ ...serviceEnv(service, options.agent, ctx), ...extra });
  return files;
}

export async function writeExport(dir: string, files: Record<string, string>): Promise<void> {
  await mkdir(dir, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    await writeFile(join(dir, name), content);
    if (name.endsWith('.sh')) await chmod(join(dir, name), 0o755);
  }
}

function readme(options: ExportOptions): string {
  return `# Twake.ai MCP servers for "${options.agent}"

Generated by \`mcp-twake-ai export\`. ${options.raw ? 'Each entry starts an MCP server with its full environment.' : 'Each entry starts `mcp-twake-ai run <service> --agent ' + options.agent + '`, which builds the environment itself.'} No file holds a secret: the servers get their tokens from \`mcp-twake-ai token\`.

| File | For |
|---|---|
| \`mcpServers.json\` | Claude Desktop, Cursor, Windsurf, Cline, Gemini CLI…: merge into their \`mcpServers\` |
| \`vscode-mcp.json\` | VS Code: merge into the \`servers\` of your user \`mcp.json\` |
| \`hermes.yaml\` | Hermes Agent: merge into \`mcp_servers\` of \`~/.hermes/config.yaml\` |
| \`codex.toml\` | Codex CLI: put its tables in \`~/.codex/config.toml\`, replacing the \`[mcp_servers.twake-*]\` tables of an earlier export |
| \`claude-code.sh\` | Claude Code: run it once |
| \`<service>.env\`, \`commands.txt\` | anything else: the command, its arguments and its environment (\`.env\` files are POSIX shell: \`set -a; . ./mail.env; set +a\`) |

- **Approvals:** every write is approved by you first, through MCP elicitation. In an agent without elicitation, reads work and writes are refused. Set \`<PREFIX>_APPROVAL=client\` only if the agent itself asks you to confirm every write tool.
- **Hermes:** keep \`timeout: 420\` and \`elicitation.timeout: 300\`; the servers wait 330 s for your answer.
- **Twake Chat:** this export uses the device of "${options.agent}". Use another \`--agent\` for every other agent: one encryption device cannot run in two agents at once.
- **Paths:** the commands use absolute paths, because some agents do not see your \`PATH\`. Export again after moving Node.js, and after signing in to Twake Chat again (\`--raw\` exports name its device's store). \`claude-code.sh\` can be run again: it replaces its entries.
- **Windows:** the Twake.ai MCP servers run their token command through \`/bin/sh\` for now, so these entries work on Linux and macOS only.
`;
}
